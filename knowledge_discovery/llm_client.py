def generate_insights(
    summary: dict,
    mode: str = "auto",
    analyst_question: str = "",
    client=None,
    write_audit: bool = True,
    provider: Optional[str] = None,
) -> InsightResult:
    """Produce an explanation of `summary`.

    mode:     "live", "demo", or "auto" (live if a key is configured, else demo).
    provider: "anthropic", "gemini", or None/"auto" (see resolve_provider).
    client:   optional pre-built SDK client (tests use fakes). When a client is
              passed without a provider it is treated as an Anthropic client.
    """
    question = (analyst_question or "")[:MAX_QUESTION_CHARS]
    user_message = build_user_message(summary, question)
    payload_hash = hashlib.sha256((SYSTEM_PROMPT + user_message).encode("utf-8")).hexdigest()

    if client is not None and provider in (None, "auto"):
        provider = "anthropic"
    provider = resolve_provider(provider)

    if mode == "auto":
        mode = "live" if (client is not None or live_mode_available(provider)) else "demo"

    start = time.perf_counter()
    if mode == "demo":
        result = InsightResult(mode="demo", ok=True, text=_demo_report(summary), payload_sha256=payload_hash)
    elif mode == "live":
        live = _generate_live_gemini if provider == "gemini" else _generate_live_anthropic
        result = live(client, user_message, payload_hash)
        result.provider = provider
    else:
        raise ValueError(f"Unknown mode '{mode}' (expected live, demo or auto).")
    result.elapsed_seconds = round(time.perf_counter() - start, 2)

    if write_audit:
        result.audit_path = _write_audit({
            "run_id": summary["dataset"]["run_id"],
            "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
            "mode": result.mode,
            "provider": result.provider,
            "is_llm_output": result.mode == "live" and result.ok,
            "system_prompt": SYSTEM_PROMPT,
            "user_message": user_message,
            "user_message_sent_to_api": result.api_request_attempted,
            "result": asdict(result),
        })
    return result


def _finish(text, stop_reason, model, request_id, usage, payload_hash) -> InsightResult:
    """Shared post-processing of a provider response."""
    common = dict(mode="live", model=model, stop_reason=stop_reason, request_id=request_id, usage=usage,
                  payload_sha256=payload_hash, api_request_attempted=True)
    if stop_reason == "refusal":
        return InsightResult(ok=False, text="", error="The model declined this request (stop_reason=refusal).",
                             **common)
    if not text.strip():
        return InsightResult(ok=False, text="", error=f"The model returned no text (stop_reason={stop_reason}).",
                             **common)
    note = "\n\n_Note: output was truncated at max_tokens._" if stop_reason == "max_tokens" else ""
    return InsightResult(ok=True, text=text + note, **common)


def _fail(msg: str, payload_hash: str, attempted: bool = True) -> InsightResult:
    return InsightResult(mode="live", ok=False, text="", error=msg, payload_sha256=payload_hash,
                         api_request_attempted=attempted)


def _generate_live_anthropic(client, user_message: str, payload_hash: str) -> InsightResult:
    try:
        import anthropic
    except ImportError:
        return _fail("The 'anthropic' package is not installed (pip install -r requirements.txt).",
                     payload_hash, attempted=False)

    if client is None:
        if not live_mode_available("anthropic"):
            return _fail("ANTHROPIC_API_KEY is not set. Add it to your environment or a local .env "
                         "file (see .env.example), use the Gemini provider, or use Demo Mode.",
                         payload_hash, attempted=False)
        client = anthropic.Anthropic()  # reads ANTHROPIC_API_KEY from the environment

    try:
        out = _call_claude(client, SYSTEM_PROMPT, user_message)
    except anthropic.AuthenticationError:
        return _fail("Authentication failed: the API key was rejected. Check ANTHROPIC_API_KEY.", payload_hash)
    except anthropic.PermissionDeniedError:
        return _fail("The API key does not have permission to use this model.", payload_hash)
    except anthropic.NotFoundError:
        return _fail(f"Model not found. Check KD_MODEL (currently '{model_for('anthropic')}').", payload_hash)
    except anthropic.RateLimitError:
        return _fail("Rate limited by the Anthropic API. Wait a minute and try again.", payload_hash)
    except anthropic.BadRequestError as e:
        return _fail(f"Request rejected by the API (400): {getattr(e, 'message', e)}", payload_hash)
    except anthropic.APIStatusError as e:
        return _fail(f"Anthropic API error (HTTP {e.status_code}). Try again later.", payload_hash)
    except anthropic.APIConnectionError:
        return _fail("Could not reach the Anthropic API. Check your internet connection or proxy.", payload_hash)
    return _finish(*out, payload_hash)


def _generate_live_gemini(client, user_message: str, payload_hash: str) -> InsightResult:
    try:
        from google import genai
        from google.genai import errors as genai_errors
        from google.genai import types
    except ImportError:
        return _fail("The 'google-genai' package is not installed (pip install -r requirements.txt).",
                     payload_hash, attempted=False)

    if client is None:
        key = _gemini_key()
        if not key:
            return _fail("GEMINI_API_KEY is not set. Add it to your environment or a local .env "
                         "file (see .env.example), use the Claude provider, or use Demo Mode.",
                         payload_hash, attempted=False)
        client = genai.Client(api_key=key, http_options=types.HttpOptions(
            timeout=GEMINI_TIMEOUT_MS,
            # transient overload / rate limits: 3 attempts with exponential back-off
            retry_options=types.HttpRetryOptions(attempts=3, initial_delay=2.0, max_delay=20.0,
                                                 http_status_codes=[429, 500, 502, 503, 504])))

    model = model_for("gemini")
    try:
        out = _call_gemini(client, SYSTEM_PROMPT, user_message)
    except genai_errors.ClientError as e:
        msg = str(getattr(e, "message", "") or "")
        if e.code in (401, 403) or (e.code == 400 and "api key" in msg.lower()):
            return _fail("Authentication failed: the Gemini API key was rejected or lacks access. "
                         "Check GEMINI_API_KEY.", payload_hash)
        if e.code == 404:
            return _fail(f"Model not found or retired. Check KD_GEMINI_MODEL (currently '{model}'). "
                         f"Google says: {msg[:200]}", payload_hash)
        if e.code == 429:
            return _fail("Rate limited or quota exceeded on the Gemini API. Wait and try again, "
                         "or check your quota in Google AI Studio.", payload_hash)
        return _fail(f"Request rejected by the Gemini API ({e.code}): {msg[:300]}", payload_hash)
    except genai_errors.ServerError as e:
        hint = (" The model is overloaded; try again shortly or set KD_GEMINI_MODEL to another Flash model."
                if e.code == 503 else "")
        return _fail(f"Gemini API error (HTTP {e.code}). Try again later.{hint}", payload_hash)
    except genai_errors.APIError as e:
        return _fail(f"Gemini API error ({getattr(e, 'code', '?')}). Try again later.", payload_hash)
    except _transport_errors() as e:  # DNS, TLS, timeouts raised by the HTTP layer
        return _fail(f"Could not reach the Gemini API ({type(e).__name__}). "
                     "Check your internet connection or proxy.", payload_hash)
    return _finish(*out, payload_hash)


def _transport_errors() -> tuple:
    """Network-level exception types of the HTTP stacks google-genai may use."""
    errs = [ConnectionError, TimeoutError]
    for mod in ("httpx", "httpx2"):
        try:
            errs.append(__import__(mod).TransportError)
        except (ImportError, AttributeError):
            pass
    try:
        import requests
        errs.append(requests.exceptions.ConnectionError)
        errs.append(requests.exceptions.Timeout)
    except ImportError:
        pass
    return tuple(errs)
