"""
knowledge_discovery/llm_client.py

Sends the aggregate summary to Claude (live mode) or produces a clearly
labelled rule-based explanation (demo mode), and writes an audit record
of exactly what was sent and received.

Modes:
  - "live": requires ANTHROPIC_API_KEY (read from the environment or a
    local, git-ignored .env file). The key is never placed in the prompt,
    the audit log, or the UI.
  - "demo": no network call. The text is generated deterministically by
    `_demo_report()` from the same summary and is labelled everywhere as
    NOT being LLM output.

Configuration (environment variables, see .env.example):
  ANTHROPIC_API_KEY        required for live mode
  KD_MODEL                 default "claude-opus-5-5"
  KD_EFFORT                default "medium"  (low | medium | high)
  KD_MAX_TOKENS            default 16000
  KD_SERVER_FALLBACK       default "1"; set "0" to disable the server-side
                           refusal fallback (Claude API only)
"""

from __future__ import annotations

import hashlib
import json
import os
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Optional

from knowledge_discovery.prompts import PROMPT_VERSION, SYSTEM_PROMPT, build_user_message

PROJECT_ROOT = Path(__file__).resolve().parent.parent
AUDIT_DIR = PROJECT_ROOT / "results" / "llm_insights"

DEFAULT_MODEL = "claude-opus-5-5"
FALLBACK_BETA = "server-side-fallback-2026-07-01"
MAX_QUESTION_CHARS = 500

DEMO_BANNER = (
    "> **DEMO MODE — rule-based template output, NOT generated by an LLM.** "
    "No API call was made. Configure ANTHROPIC_API_KEY to obtain a real model response."
)


def _load_dotenv_if_present():
    try:
        from dotenv import load_dotenv
    except ImportError:
        return
    load_dotenv(PROJECT_ROOT / ".env", override=False)


def live_mode_available() -> bool:
    _load_dotenv_if_present()
    return bool(os.environ.get("ANTHROPIC_API_KEY", "").strip())


@dataclass
class InsightResult:
    mode: str                       # "live" | "demo"
    ok: bool
    text: str
    model: Optional[str] = None
    error: Optional[str] = None
    stop_reason: Optional[str] = None
    request_id: Optional[str] = None
    usage: dict = field(default_factory=dict)
    prompt_version: str = PROMPT_VERSION
    payload_sha256: str = ""
    elapsed_seconds: float = 0.0
    audit_path: Optional[str] = None
    api_request_attempted: bool = False  # True once a request to the API was actually issued


# ---------------------------------------------------------------------------
def _demo_report(summary: dict) -> str:
    """Deterministic, template-based explanation. Never presented as LLM output."""
    ds = summary["dataset"]
    q = summary["generator_quality_context"]
    fid = q["fidelity_vs_real_training_data"]
    lines = [DEMO_BANNER, "", "## Overview",
             f"Synthetic dataset `{ds['run_id']}` from **{ds['generator']}** "
             f"({ds['formal_guarantee'] or 'privacy statement unavailable'}), "
             f"{ds['n_synthetic_rows']} rows, {len(ds['numerical_columns'])} numerical and "
             f"{len(ds['categorical_columns'])} categorical columns. "
             f"Recorded quality: mean KS = {fid['mean_ks_statistic_numerical']}, mean TVD = "
             f"{fid['mean_total_variation_distance_categorical']}, 3-way marginal L1 = "
             f"{fid['three_way_marginal_mean_l1_error']}, best TSTR F1 = {q['best_tstr_f1_on_real_test_set']}, "
             f"MIA AUC = {q['membership_inference_attack_auc']}.", "", "## Key patterns"]
    ta = summary.get("target_analysis")
    if ta:
        lines.append(f"Overall share of `{ta['target_column']} = {ta['positive_class']}`: "
                     f"{ta['overall_positive_rate']}.")
        spreads = []
        for col, groups in ta["positive_rate_by_column"].items():
            rates = [g["positive_rate"] for g in groups.values() if g["positive_rate"] is not None]
            if len(rates) >= 2:
                hi = max(groups.items(), key=lambda kv: kv[1]["positive_rate"])
                lo = min(groups.items(), key=lambda kv: kv[1]["positive_rate"])
                spreads.append((max(rates) - min(rates), col, hi, lo))
        for spread, col, hi, lo in sorted(spreads, reverse=True)[:5]:
            lines.append(f"- `{col}`: highest rate {hi[1]['positive_rate']} for `{hi[0]}`, lowest "
                         f"{lo[1]['positive_rate']} for `{lo[0]}` (spread {round(spread, 3)}).")
    lines += ["", "## Relationships between attributes"]
    for a in summary["strongest_categorical_associations"][:5]:
        lines.append(f"- `{a['columns'][0]}` ↔ `{a['columns'][1]}`: Cramér's V = {a['cramers_v']}")
    for a in summary["strongest_numerical_correlations"][:3]:
        lines.append(f"- `{a['columns'][0]}` ↔ `{a['columns'][1]}`: Pearson r = {a['pearson_r']}")
    lines += ["", "## Possible insights and hypotheses",
              "The template lists the largest group differences above; a live LLM response would "
              "interpret them. Any such pattern is a hypothesis to validate on governed real data.",
              "", "## Limitations and caveats",
              "- Patterns come from DP synthetic data and inherit DP noise and generator bias.",
              "- Numerical values were reconstructed uniformly within bins, so numeric detail is approximate.",
              f"- {summary['privacy_manifest']['cells_suppressed_below_min_count']} small cells "
              f"(< {summary['privacy_manifest']['min_cell_count']} rows) were suppressed.",
              "- Associations are not causal, and the statistics are not an additional DP release."]
    return "\n".join(lines)


def _write_audit(record: dict) -> str:
    AUDIT_DIR.mkdir(parents=True, exist_ok=True)
    path = AUDIT_DIR / f"{time.strftime('%Y%m%d-%H%M%S')}_{record['mode']}_{record['run_id']}.json"
    path.write_text(json.dumps(record, indent=2, default=str), encoding="utf-8")
    return str(path)


def _call_claude(client, system: str, user_message: str) -> tuple:
    """One Messages API call. Returns (text, stop_reason, model, request_id, usage)."""
    model = os.environ.get("KD_MODEL", DEFAULT_MODEL)
    kwargs = dict(
        model=model,
        max_tokens=int(os.environ.get("KD_MAX_TOKENS", "16000")),
        system=system,
        messages=[{"role": "user", "content": user_message}],
        output_config={"effort": os.environ.get("KD_EFFORT", "medium")},
    )
    if os.environ.get("KD_SERVER_FALLBACK", "1") != "0":
        response = client.beta.messages.create(betas=[FALLBACK_BETA], fallbacks="default", **kwargs)
    else:
        response = client.messages.create(**kwargs)
    text = "\n".join(b.text for b in response.content if getattr(b, "type", None) == "text")
    usage = {}
    if getattr(response, "usage", None) is not None:
        usage = {k: getattr(response.usage, k, None) for k in ("input_tokens", "output_tokens")}
    return text, response.stop_reason, getattr(response, "model", model), getattr(response, "_request_id", None), usage


def generate_insights(
    summary: dict,
    mode: str = "auto",
    analyst_question: str = "",
    client=None,
    write_audit: bool = True,
) -> InsightResult:
    """Produce an explanation of `summary`.

    mode: "live", "demo", or "auto" (live if a key is configured, else demo).
    client: optional pre-built Anthropic client (used by tests with a fake).
    """
    question = (analyst_question or "")[:MAX_QUESTION_CHARS]
    user_message = build_user_message(summary, question)
    payload_hash = hashlib.sha256((SYSTEM_PROMPT + user_message).encode("utf-8")).hexdigest()

    if mode == "auto":
        mode = "live" if (client is not None or live_mode_available()) else "demo"

    start = time.perf_counter()
    if mode == "demo":
        result = InsightResult(mode="demo", ok=True, text=_demo_report(summary), payload_sha256=payload_hash)
    elif mode == "live":
        result = _generate_live(client, user_message, payload_hash)
    else:
        raise ValueError(f"Unknown mode '{mode}' (expected live, demo or auto).")
    result.elapsed_seconds = round(time.perf_counter() - start, 2)

    if write_audit:
        result.audit_path = _write_audit({
            "run_id": summary["dataset"]["run_id"],
            "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
            "mode": result.mode,
            "is_llm_output": result.mode == "live" and result.ok,
            "system_prompt": SYSTEM_PROMPT,
            "user_message": user_message,
            "user_message_sent_to_api": result.api_request_attempted,
            "result": asdict(result),
        })
    return result


def _generate_live(client, user_message: str, payload_hash: str) -> InsightResult:
    try:
        import anthropic
    except ImportError:
        return InsightResult(mode="live", ok=False, text="", payload_sha256=payload_hash,
                             error="The 'anthropic' package is not installed (pip install -r requirements.txt).")

    if client is None:
        if not live_mode_available():
            return InsightResult(mode="live", ok=False, text="", payload_sha256=payload_hash,
                                 error="ANTHROPIC_API_KEY is not set. Add it to your environment or a local .env "
                                       "file (see .env.example), or use Demo Mode.")
        client = anthropic.Anthropic()  # reads ANTHROPIC_API_KEY from the environment

    def fail(msg):
        return InsightResult(mode="live", ok=False, text="", error=msg, payload_sha256=payload_hash,
                             api_request_attempted=True)

    try:
        text, stop_reason, model, request_id, usage = _call_claude(client, SYSTEM_PROMPT, user_message)
    except anthropic.AuthenticationError:
        return fail("Authentication failed: the API key was rejected. Check ANTHROPIC_API_KEY.")
    except anthropic.PermissionDeniedError:
        return fail("The API key does not have permission to use this model.")
    except anthropic.NotFoundError:
        return fail(f"Model not found. Check KD_MODEL (currently '{os.environ.get('KD_MODEL', DEFAULT_MODEL)}').")
    except anthropic.RateLimitError:
        return fail("Rate limited by the Anthropic API. Wait a minute and try again.")
    except anthropic.BadRequestError as e:
        return fail(f"Request rejected by the API (400): {getattr(e, 'message', e)}")
    except anthropic.APIStatusError as e:
        return fail(f"Anthropic API error (HTTP {e.status_code}). Try again later.")
    except anthropic.APIConnectionError:
        return fail("Could not reach the Anthropic API. Check your internet connection or proxy.")

    if stop_reason == "refusal":
        return InsightResult(mode="live", ok=False, text="", model=model, stop_reason=stop_reason,
                             request_id=request_id, usage=usage, payload_sha256=payload_hash, api_request_attempted=True,
                             error="The model declined this request (stop_reason=refusal).")
    if not text.strip():
        return InsightResult(mode="live", ok=False, text="", model=model, stop_reason=stop_reason,
                             request_id=request_id, usage=usage, payload_sha256=payload_hash, api_request_attempted=True,
                             error=f"The model returned no text (stop_reason={stop_reason}).")
    note = "\n\n_Note: output was truncated at max_tokens._" if stop_reason == "max_tokens" else ""
    return InsightResult(mode="live", ok=True, text=text + note, model=model, stop_reason=stop_reason,
                         request_id=request_id, usage=usage, payload_sha256=payload_hash, api_request_attempted=True)
