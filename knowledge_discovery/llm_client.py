"""
knowledge_discovery/llm_client.py

Sends the aggregate summary to an LLM (live mode) or produces a clearly
labelled rule-based explanation (demo mode), and writes an audit record
of exactly what was sent and received.

Providers (live mode):
  - "anthropic": Claude via the official `anthropic` SDK (Messages API).
  - "gemini":    Google Gemini via the official `google-genai` SDK.
Both receive the identical system prompt and aggregate-only user message,
and their responses are normalised into the same InsightResult, so demo
mode, auditing and the privacy guards are provider-independent.

Modes:
  - "live": requires the chosen provider's API key (from the environment or
    a local, git-ignored .env file). Keys are never placed in the prompt,
    the audit log, or the UI.
  - "demo": no network call. The text is generated deterministically by
    `_demo_report()` from the same summary and is labelled everywhere as
    NOT being LLM output.

Configuration (environment variables, see .env.example):
  KD_PROVIDER              "auto" (default) | "anthropic" | "gemini".
                           auto = Claude if ANTHROPIC_API_KEY is set, else
                           Gemini if GEMINI_API_KEY / GOOGLE_API_KEY is set.
  ANTHROPIC_API_KEY        Claude key
  GEMINI_API_KEY           Gemini key (GOOGLE_API_KEY is also accepted)
  KD_MODEL                 Claude model, default "claude-opus-5-5"
  KD_GEMINI_MODEL          Gemini model, default "gemini-flash-latest" (alias; the served
                           version is recorded), e.g. pin "gemini-3.6-flash"
  KD_EFFORT                Claude effort, default "medium" (low | medium | high)
  KD_MAX_TOKENS            default 16000 (Gemini: includes thinking tokens)
  KD_SERVER_FALLBACK       default "1"; "0" disables Claude's server-side
                           refusal fallback (Claude API only)
"""

from __future__ import annotations

import hashlib
import json
import os
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Optional

from knowledge_discovery.prompts import PROMPT_VERSION, SYSTEM_PROMPT, build_user_message

PROJECT_ROOT = Path(__file__).resolve().parent.parent
AUDIT_DIR = PROJECT_ROOT / "results" / "llm_insights"

PROVIDERS = ("anthropic", "gemini")
DEFAULT_MODEL = "claude-opus-5-5"
# Google retires pinned Gemini versions quickly (gemini-2.5-flash is closed to new users),
# so the default is Google's current-Flash alias; the version that actually served each
# request is recorded in InsightResult.model and the audit record. Pin with KD_GEMINI_MODEL.
DEFAULT_GEMINI_MODEL = "gemini-flash-latest"
FALLBACK_BETA = "server-side-fallback-2026-07-01"
MAX_QUESTION_CHARS = 500
GEMINI_TIMEOUT_MS = 180_000

# Gemini finish reasons that mean "the model declined / output was withheld".
_GEMINI_BLOCKED = {"SAFETY", "RECITATION", "BLOCKLIST", "PROHIBITED_CONTENT", "SPII"}

DEMO_BANNER = (
    "> **DEMO MODE — rule-based template output, NOT generated by an LLM.** "
    "No API call was made. Configure ANTHROPIC_API_KEY or GEMINI_API_KEY to obtain a real model response."
)


def _load_dotenv_if_present():
    try:
        from dotenv import load_dotenv
    except ImportError:
        return
    load_dotenv(PROJECT_ROOT / ".env", override=False)


def _real(value: str) -> str:
    """Treat unfilled .env.example placeholders ("your-...-here") as unset."""
    value = (value or "").strip()
    return "" if value.lower().startswith("your-") else value


def _anthropic_key() -> str:
    return _real(os.environ.get("ANTHROPIC_API_KEY", ""))


def _gemini_key() -> str:
    return _real(os.environ.get("GEMINI_API_KEY", "")) or _real(os.environ.get("GOOGLE_API_KEY", ""))


def resolve_provider(provider: Optional[str] = None) -> str:
    """Explicit argument > KD_PROVIDER > auto-detection from configured keys."""
    _load_dotenv_if_present()
    choice = (provider or os.environ.get("KD_PROVIDER", "auto")).strip().lower()
    if choice in PROVIDERS:
        return choice
    if choice != "auto":
        raise ValueError(f"Unknown provider '{choice}' (expected auto, anthropic or gemini).")
    if _anthropic_key():
        return "anthropic"
    if _gemini_key():
        return "gemini"
    return "anthropic"


def live_mode_available(provider: Optional[str] = None) -> bool:
    _load_dotenv_if_present()
    p = resolve_provider(provider)
    return bool(_anthropic_key() if p == "anthropic" else _gemini_key())


def model_for(provider: str) -> str:
    return os.environ.get("KD_GEMINI_MODEL", DEFAULT_GEMINI_MODEL) if provider == "gemini" \
        else os.environ.get("KD_MODEL", DEFAULT_MODEL)


@dataclass
class InsightResult:
    mode: str                       # "live" | "demo"
    ok: bool
    text: str
    provider: Optional[str] = None  # "anthropic" | "gemini" (live mode only)
    model: Optional[str] = None
    error: Optional[str] = None
    stop_reason: Optional[str] = None  # normalised: end_turn | max_tokens | refusal | other
    request_id: Optional[str] = None
    usage: dict = field(default_factory=dict)
    prompt_version: str = PROMPT_VERSION
    payload_sha256: str = ""
    elapsed_seconds: float = 0.0
    audit_path: Optional[str] = None
    api_request_attempted: bool = False  # True once a request to the API was actually issued


