def _demo_report(summary: dict) -> str:
    """Deterministic, template-based explanation. Never presented as LLM output."""
    ds = summary["dataset"]
    q = summary.get("generator_quality_context")
    overview = (f"Synthetic dataset `{ds['run_id']}` from **{ds['generator']}** "
                f"({ds['formal_guarantee'] or 'privacy statement unavailable'}), "
                f"{ds['n_synthetic_rows']} rows, {len(ds['numerical_columns'])} numerical and "
                f"{len(ds['categorical_columns'])} categorical columns.")
    if q:
        fid = q["fidelity_vs_real_training_data"]
        overview += (f" Recorded quality: mean KS = {fid['mean_ks_statistic_numerical']}, mean TVD = "
                     f"{fid['mean_total_variation_distance_categorical']}, 3-way marginal L1 = "
                     f"{fid['three_way_marginal_mean_l1_error']}, best TSTR F1 = "
                     f"{q['best_tstr_f1_on_real_test_set']}, MIA AUC = {q['membership_inference_attack_auc']}.")
    else:
        overview += " Quality metrics were withheld from this payload."
    lines = [DEMO_BANNER, "", "## Overview", overview, "", "## Key patterns"]
    ta = summary.get("target_analysis")
    if ta:
        lines.append(f"Overall share of `{ta['target_column']} = {ta['positive_class']}`: "
                     f"{ta['overall_positive_rate']}.")
        spreads = []
        for col, groups in ta["positive_rate_by_column"].items():
            rates = [g["positive_rate"] for g in groups.values() if g["positive_rate"] is not None]
            if len(rates) >= 2:
                hi = max(groups.items(), key=lambda kv: kv[1]["positive_rate"])
                lo = min(groups.items(), key=lambda kv: kv[1]["positive_rate"])
                spreads.append((max(rates) - min(rates), col, hi, lo))
        for spread, col, hi, lo in sorted(spreads, reverse=True)[:5]:
            lines.append(f"- `{col}`: highest rate {hi[1]['positive_rate']} for `{hi[0]}`, lowest "
                         f"{lo[1]['positive_rate']} for `{lo[0]}` (spread {round(spread, 3)}).")
    lines += ["", "## Relationships between attributes"]
    for a in summary["strongest_categorical_associations"][:5]:
        lines.append(f"- `{a['columns'][0]}` ↔ `{a['columns'][1]}`: Cramér's V = {a['cramers_v']}")
    for a in summary["strongest_numerical_correlations"][:3]:
        lines.append(f"- `{a['columns'][0]}` ↔ `{a['columns'][1]}`: Pearson r = {a['pearson_r']}")
    lines += ["", "## Possible insights and hypotheses",
              "The template lists the largest group differences above; a live LLM response would "
              "interpret them. Any such pattern is a hypothesis to validate on governed real data.",
              "", "## Limitations and caveats",
              "- Patterns come from DP synthetic data and inherit DP noise and generator bias.",
              "- Numerical values were reconstructed uniformly within bins, so numeric detail is approximate.",
              f"- {summary['privacy_manifest']['cells_suppressed_below_min_count']} small cells "
              f"(< {summary['privacy_manifest']['min_cell_count']} rows) were suppressed.",
              "- Associations are not causal, and the statistics are not an additional DP release."]
    return "\n".join(lines)


def _write_audit(record: dict) -> str:
    AUDIT_DIR.mkdir(parents=True, exist_ok=True)
    path = AUDIT_DIR / f"{time.strftime('%Y%m%d-%H%M%S')}_{record['mode']}_{record['run_id']}.json"
    path.write_text(json.dumps(record, indent=2, default=str), encoding="utf-8")
    return str(path)


