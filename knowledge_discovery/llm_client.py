# Provider calls. Each returns (text, stop_reason, model, request_id, usage)
# with stop_reason normalised to end_turn | max_tokens | refusal | <other>.
def _call_claude(client, system: str, user_message: str) -> tuple:
    """One Messages API call."""
    model = model_for("anthropic")
    kwargs = dict(
        model=model,
        max_tokens=int(os.environ.get("KD_MAX_TOKENS", "16000")),
        system=system,
        messages=[{"role": "user", "content": user_message}],
        output_config={"effort": os.environ.get("KD_EFFORT", "medium")},
    )
    if os.environ.get("KD_SERVER_FALLBACK", "1") != "0":
        response = client.beta.messages.create(betas=[FALLBACK_BETA], fallbacks="default", **kwargs)
    else:
        response = client.messages.create(**kwargs)
    text = "\n".join(b.text for b in response.content if getattr(b, "type", None) == "text")
    usage = {}
    if getattr(response, "usage", None) is not None:
        usage = {k: getattr(response.usage, k, None) for k in ("input_tokens", "output_tokens")}
    return text, response.stop_reason, getattr(response, "model", model), getattr(response, "_request_id", None), usage


def _call_gemini(client, system: str, user_message: str) -> tuple:
    """One generate_content call (Gemini API, google-genai SDK)."""
    from google.genai import types

    model = model_for("gemini")
    config = types.GenerateContentConfig(
        system_instruction=system,
        max_output_tokens=int(os.environ.get("KD_MAX_TOKENS", "16000")),
    )
    response = client.models.generate_content(model=model, contents=user_message, config=config)

    feedback = getattr(response, "prompt_feedback", None)
    if feedback is not None and getattr(feedback, "block_reason", None):
        return "", "refusal", model, getattr(response, "response_id", None), {}

    candidates = getattr(response, "candidates", None) or []
    text, finish = "", None
    if candidates:
        cand = candidates[0]
        finish = getattr(getattr(cand, "finish_reason", None), "name", None) or str(getattr(cand, "finish_reason", ""))
        parts = getattr(getattr(cand, "content", None), "parts", None) or []
        # Keep answer text only; never surface internal "thought" parts.
        text = "".join(p.text for p in parts if getattr(p, "text", None) and not getattr(p, "thought", False))

    if finish in _GEMINI_BLOCKED:
        stop = "refusal"
    elif finish == "MAX_TOKENS":
        stop = "max_tokens"
    elif finish in ("STOP", None, ""):
        stop = "end_turn"
    else:
        stop = finish.lower()

    meta = getattr(response, "usage_metadata", None)
    usage = {}
    if meta is not None:
        usage = {"input_tokens": getattr(meta, "prompt_token_count", None),
                 "output_tokens": getattr(meta, "candidates_token_count", None),
                 "thinking_tokens": getattr(meta, "thoughts_token_count", None)}
    return text, stop, getattr(response, "model_version", None) or model, getattr(response, "response_id", None), usage


