"""
analysis/llm_case_study.py

OFFLINE fact-check of the two real Gemini responses recorded on 2026-10-11
(AIM eps=3 seed 42 and PrivBayes eps=3 seed 42, model gemini-3.8-flash).

Each claim quoted from an LLM response is checked twice:
  * faithfulness - does it match the aggregate payload the LLM was sent?
  * real-data agreement - does the same statistic hold on the REAL training
    split?  (The LLM never sees the real data; it is used here only to score.)

MST eps=3 seed 42 is included as a third synthetic reference (no LLM call).

The LLM response texts themselves are exported to evidence/llm_responses/ when the
git-ignored audit records in results/llm_insights/ are present.

Run from the project root:  python -m analysis.llm_case_study
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from analysis.verify_results import setup_data  # noqa: E402
from knowledge_discovery.catalog import SyntheticDatasetInfo, list_dp_synthetic_datasets, load_synthetic_dataset  # noqa: E402
from knowledge_discovery.summarizer import _cramers_v, build_aggregate_summary  # noqa: E402

OUT = ROOT / "results" / "verified"
EVIDENCE = ROOT / "evidence" / "llm_responses"
AUDIT = ROOT / "results" / "llm_insights"
RUNS = ["adult_example_AIM_eps3.0_seed42", "adult_example_PrivBayes_eps3.0_seed42", "adult_example_MST_eps3.0_seed42"]
LIVE_RECORDS = {
    "adult_example_AIM_eps3.0_seed42": "20261011-224948_live_adult_example_AIM_eps3.0_seed42.json",
    "adult_example_PrivBayes_eps3.0_seed42": "20261011-225231_live_adult_example_PrivBayes_eps3.0_seed42.json",
}

# Claims quoted from the two responses (claim text, statistic key, value the LLM stated).
CLAIMS = [
    ("adult_example_AIM_eps3.0_seed42", "Female >50K rate 25.4% vs Male 23.3% (women higher)", "female_rate", 0.254),
    ("adult_example_AIM_eps3.0_seed42", "", "male_rate", 0.233),
    ("adult_example_AIM_eps3.0_seed42", "education-race Cramer's V = 0.493", "edu_race_v", 0.493),
    ("adult_example_AIM_eps3.0_seed42", "Cells suppressed below a count of 8", "min_cell_count", 8),
    ("adult_example_AIM_eps3.0_seed42", "Overall >50K rate 24.0%", "overall_rate", 0.240),
    ("adult_example_PrivBayes_eps3.0_seed42", "Male >50K rate 31.6% vs Female 11.5%", "male_rate", 0.316),
    ("adult_example_PrivBayes_eps3.0_seed42", "", "female_rate", 0.115),
    ("adult_example_PrivBayes_eps3.0_seed42", "'12th' grade >50K rate 67.4% - flagged as implausible DP artefact",
     "rate_12th", 0.674),
    ("adult_example_PrivBayes_eps3.0_seed42", "Two cells suppressed below 20", "min_cell_count", 20),
    ("adult_example_PrivBayes_eps3.0_seed42", "Overall >50K rate 24.6%", "overall_rate", 0.246),
]


def _stats(df: pd.DataFrame, summary: dict | None) -> dict:
    y = (df["income"].astype(str).str.strip() == ">50K").astype(float)
    sex = df["sex"].astype(str).str.strip()
    edu = df["education"].astype(str).str.strip()
    out = {
        "overall_rate": round(y.mean(), 3),
        "female_rate": round(y[sex == "Female"].mean(), 3),
        "male_rate": round(y[sex == "Male"].mean(), 3),
        "rate_12th": round(y[edu == "12th"].mean(), 3) if (edu == "12th").any() else None,
        "edu_race_v": round(_cramers_v(df["education"], df["race"]), 3),
    }
    if summary is not None:
        out["min_cell_count"] = summary["privacy_manifest"]["min_cell_count"]
        out["cells_suppressed"] = summary["privacy_manifest"]["cells_suppressed_below_min_count"]
    return out


def _export_evidence():
    EVIDENCE.mkdir(parents=True, exist_ok=True)
    written = []
    for run_id, name in LIVE_RECORDS.items():
        path = AUDIT / name
        if not path.exists():
            continue
        rec = json.loads(path.read_text(encoding="utf-8"))
        r = rec["result"]
        head = (f"# Real LLM output - {run_id}\n\n"
                f"> **This text WAS generated by an LLM** (provider `{r['provider']}`, model `{r['model']}`) "
                f"on {rec['timestamp']} from the aggregate-only payload of a DP synthetic dataset. "
                f"It is reproduced unedited for transparency. It is a set of hypotheses, not verified findings; "
                f"see `results/verified/llm_case_study.csv` for the fact-check.\n\n"
                f"| Field | Value |\n|---|---|\n"
                f"| payload SHA-256 | `{r['payload_sha256']}` |\n| request id | `{r['request_id']}` |\n"
                f"| tokens (input / output / thinking) | {r['usage'].get('input_tokens')} / "
                f"{r['usage'].get('output_tokens')} / {r['usage'].get('thinking_tokens')} |\n"
                f"| latency | {r['elapsed_seconds']} s |\n| stop reason | {r['stop_reason']} |\n\n---\n\n")
        out = EVIDENCE / f"{run_id}_gemini.md"
        out.write_text(head + r["text"] + "\n", encoding="utf-8")
        written.append(out)
    return written


def main():
    _, train, _, pp, _, _ = setup_data()
    real = _stats(pp.transform_continuous(train), None)
    infos = {d.run_id: d for d in list_dp_synthetic_datasets()}
    syn = {}
    for run_id in RUNS:
        df = load_synthetic_dataset(infos[run_id])
        syn[run_id] = _stats(df, build_aggregate_summary(df, infos[run_id]))

    ref = pd.DataFrame([{"dataset": "REAL train split", **real}] +
                       [{"dataset": k, **v} for k, v in syn.items()])
    ref["gender_gap_male_minus_female"] = (ref["male_rate"] - ref["female_rate"]).round(3)

    rows = []
    for run_id, claim, key, stated in CLAIMS:
        payload = syn[run_id].get(key)
        real_v = real.get(key)
        faithful = payload is not None and abs(float(payload) - float(stated)) < 0.0015
        rows.append({"run_id": run_id, "claim": claim, "statistic": key, "llm_stated": stated,
                     "payload_value": payload, "faithful_to_payload": faithful,
                     "real_train_value": real_v,
                     "abs_diff_vs_real": None if real_v is None else round(abs(float(stated) - float(real_v)), 3)})
    claims = pd.DataFrame(rows)

    OUT.mkdir(parents=True, exist_ok=True)
    ref.to_csv(OUT / "llm_case_study_reference.csv", index=False)
    claims.to_csv(OUT / "llm_case_study.csv", index=False)
    written = _export_evidence()
    print(ref.to_string(index=False))
    print()
    print(claims.to_string(index=False))
    for p in written:
        print("wrote", p.relative_to(ROOT))


if __name__ == "__main__":
    main()
